const dicts: Record<Lang, Dict> = { nb, en };

const Ctx = createContext<{ lang: Lang; t: (k: string) => string; setLang: (l: Lang) => void }>({
  lang: "nb",
  t: (k) => k,
  setLang: () => {},
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("nb");
  useEffect(() => {
    const stored = typeof window !== "undefined" ? (localStorage.getItem("tdp_lang") as Lang | null) : null;
    if (stored === "nb" || stored === "en") setLangState(stored);
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") localStorage.setItem("tdp_lang", l);
  };
  const t = (k: string) => dicts[lang][k] ?? dicts.nb[k] ?? k;
  return <Ctx.Provider value={{ lang, t, setLang }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
